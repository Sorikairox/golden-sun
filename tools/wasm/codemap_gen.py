"""Generates build/wasm/gen/code_map.ll for port/pc/codemap.c (called by tools/wasm/link.py).

The game sometimes calls code by its GBA address: function pointers read from ROM data that is not relocated,
the overlay entry table in RAM (gOverlayArea.initialize() reads the overlay function's address from the
decompressed overlay), RAM copies of ARM routines (RamCode_Load), libgcc's _call_via_rX. In wasm a function
pointer is a table index, so every indirect call goes through Port_ResolveCode (bind.py rewrites the IR), which
maps a GBA address to the wasm function: this table. One row per code symbol of the address map whose name is a
wasm function: the game's C functions (overlays as ovNNN_name, overlay 0 = main image), the far-call veneers,
and our C ports of the vendor's ARM routines, which keep the original names. Sorted by (overlay, address).
Names and addresses only.
"""
import os

import bind


def generate(out, root, sig, defined, resolve=None):
    """resolve (TLA4b, trap 66): name -> the defined function a veneer label leads to, or None. With it, a far-call
    or overlay-import veneer no C code calls by name (so it has no definition) still gets its row: translated code
    calls veneers by address. GS1's build passes none (unchanged)."""
    t = bind.Tables(root)
    rows = {}

    def fn_of(name):
        if name in defined:
            return name
        if resolve:
            tgt = resolve(name)
            if tgt and tgt in defined:
                return tgt
        return None
    for r in t.main.values():
        w = fn_of(r['name']) if r['kind'] == 'code' else None
        if not w:
            continue
        a = int(r['address'], 16) & ~1
        rows.setdefault((0, a), w)
    for (ov, name), r in t.ovl.items():
        if r['kind'] != 'code':
            continue
        w = fn_of(f'ov{ov}_{name}')
        if not w:
            continue
        rows.setdefault((int(ov, 16), int(r['address'], 16) & ~1), w)
    decls, items = set(), []
    for (ovn, a), w in sorted(rows.items()):
        base = w.split('_', 1)[1] if w.startswith('ov') and w[2:5].isalnum() and w[5:6] == '_' else w
        s = sig.get(w) or sig.get(base) or ('void', [], False)
        decls.add(f'declare {s[0]} @"{w}"({", ".join(s[1] + (["..."] if s[2] else []))})')
        items.append(f'{{ i32, i32, ptr }} {{ i32 {a}, i32 {ovn}, ptr @"{w}" }}')
    lines = ['; generated by tools/wasm/codemap_gen.py: GBA code address -> wasm function'] + sorted(decls)
    lines.append(f'@gPortCodeMapCount = constant i32 {len(items)}')
    lines.append(f'@gPortCodeMap = constant [{len(items)} x {{ i32, i32, ptr }}] [' + ', '.join(items) + ']')
    path = os.path.join(out, 'gen', 'code_map.ll')
    open(path, 'w').write('\n'.join(lines) + '\n')
    n_ov = len({o for o, _ in rows if o})
    print(f'codemap: {sum(1 for o, _ in rows if o == 0)} main-image and {sum(1 for o, _ in rows if o)} overlay '
          f'functions ({n_ov} overlays) by GBA address')
    return path
