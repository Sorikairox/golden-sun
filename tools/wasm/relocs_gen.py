"""Generates build/wasm/gen/reloc_table.ll for port/pc/relocate.c (called by tools/wasm/link.py).

Each relocated data symbol (bind.py's reloc_* buffers: code-pointer tables and the data pointing to them) gets a
row: its buffer, where its bytes are on the GBA (ROM address, or overlay-area address for an overlay's symbol),
its size, and its pointer slots. A slot is patched only when its target is a function (the wasm function
pointer) or another relocated symbol (that buffer); every other pointer stays the GBA address it was, which is
valid in the identity memory map. A function slot becomes the wasm function pointer; a data slot keeps its
addend: new = buffer + (word - GBA target). Names, addresses and offsets only.
"""
import os
import re
from collections import defaultdict

import bind


def generate(out, root, sig, defined):
    t = bind.Tables(root)
    gba = {('', r['name']): int(r['address'], 16) for r in t.main.values()}
    gba.update({(o, n): int(r['address'], 16) for (o, n), r in t.ovl.items()})
    kind = {('', r['name']): r['kind'] for r in t.main.values()}
    kind.update({(o, n): r['kind'] for (o, n), r in t.ovl.items()})
    slots = defaultdict(list)
    for r in t.relocs:
        slots[(r['overlay'], r['symbol'])].append(r)
    buffers = set()
    gen_c = os.path.join(out, 'gen', 'relocated.c')
    for line in open(gen_c):
        m = re.match(r'u8 (reloc_\w+)\[', line)
        if m:
            buffers.add(m.group(1))

    def buf_name(ov, sym):
        return 'reloc_' + (ov + '_' if ov else '') + sym

    decls, rows, slot_rows = set(), [], []
    skipped = 0
    for (ov, sym) in sorted(t.relocated):
        b = buf_name(ov, sym)
        if b not in buffers or (ov, sym) not in gba:
            skipped += 1
            continue
        first = len(slot_rows)
        for r in slots.get((ov, sym), []):
            base = r['target'].partition('+')[0]
            # the target as the game names it: an overlay's own symbol first, else the main image's
            tkey = (ov, base) if (ov, base) in gba else ('', base)
            if tkey not in gba:
                continue
            if r['target_kind'] == 'code':
                wname = f'ov{tkey[0]}_{base}' if tkey[0] else base
                if wname not in defined:
                    continue
                s = sig.get(base) or sig.get(wname) or ('void', [], False)
                decls.add(f'declare {s[0]} @"{wname}"({", ".join(s[1] + (["..."] if s[2] else []))})')
                target, is_code = f'ptr @"{wname}"', 1
            elif tkey in t.relocated and buf_name(*tkey) in buffers:
                decls.add(f'@"{buf_name(*tkey)}" = external global [0 x i8]')
                target, is_code = f'ptr @"{buf_name(*tkey)}"', 0
            else:
                continue
            slot_rows.append(f'{{ i32, i32, ptr, i32 }} {{ i32 {int(r["offset"])}, i32 {gba[tkey]}, {target}, '
                             f'i32 {is_code} }}')
        decls.add(f'@"{b}" = external global [0 x i8]')
        ovn = int(ov, 16) if ov else 0
        size = int(t.ovl[(ov, sym)]['size']) if ov else int(t.main[sym]['size'])
        rows.append(f'{{ ptr, i32, i32, i32, i32, i32 }} {{ ptr @"{b}", i32 {gba[(ov, sym)]}, i32 {size}, '
                    f'i32 {first}, i32 {len(slot_rows) - first}, i32 {ovn} }}')
    lines = ['; generated by tools/wasm/relocs_gen.py: relocated data symbols and their pointer slots'] + sorted(decls)
    lines.append(f'@gPortRelocCount = constant i32 {len(rows)}')
    lines.append(f'@gPortRelocs = constant [{len(rows)} x {{ ptr, i32, i32, i32, i32, i32 }}] [' + ', '.join(rows) + ']')
    lines.append(f'@gPortRelocSlots = constant [{len(slot_rows)} x {{ i32, i32, ptr, i32 }}] [' + ', '.join(slot_rows) + ']')
    path = os.path.join(out, 'gen', 'reloc_table.ll')
    open(path, 'w').write('\n'.join(lines) + '\n')
    print(f'relocs: {len(rows)} relocated symbols, {len(slot_rows)} patched slots ({skipped} unnamed pieces skipped)')
    return path
