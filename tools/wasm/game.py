"""Per-game settings of the wasm build (TLA2): `tools/wasm/build.py --game {tbs,tla}` sets PORT_GAME, which every
stage (and the port_src.py subprocesses) reads through this module. tbs is the default and keeps GS1's paths
exactly (build/wasm, port/*.tsv, port/symbols, port/shim), so GS1's output is unchanged.

  tbs  The Broken Seal: vendor games/tbs, tables in port/, address map port/symbols/tbs-en*.tsv (alchemy 24b72a32)
  tla  The Lost Age:    vendor games/tla, tables in port/tla/, address map port/tla/symbols/tla-en*.tsv
       (alchemy f6c08e64, compare-tla-en exact; generated by tools/ref/make_symbols.py ... tla-en), out build/wasm-tla
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../..'))
GAME = os.environ.get('PORT_GAME', 'tbs')


class _Cfg:
    pass


C = _Cfg()
C.game = GAME
if GAME == 'tbs':
    C.vendor_game = 'games/tbs'
    C.define = 'TBS_EDITION_EN'
    C.out = os.path.join(ROOT, 'build/wasm')
    C.tables = os.path.join(ROOT, 'port')                 # fn_overrides/asm_rules/c_rules/overrides.tsv
    C.symbols = os.path.join(ROOT, 'port/symbols')
    C.edition = 'tbs-en'
    C.gen = os.path.join(ROOT, 'port_work/g1/gen')        # generated ids (text/msg_ids.h)
    C.prelude = os.path.join(ROOT, 'port/shim/prelude.h')
    C.shim = os.path.join(ROOT, 'port/shim')
    C.audit = os.path.join(ROOT, 'port/tools/code_range_audit.tsv')
    C.overlay_bins = os.path.join(ROOT, 'port_work/g1/alchemy/overlays')
    C.pc_list = None                                      # every port/pc/*.c
    C.extra_cflags = []
elif GAME == 'tla':
    C.vendor_game = 'games/tla'
    C.define = 'TLA_EDITION_EN'
    C.out = os.path.join(ROOT, 'build/wasm-tla')
    C.tables = os.path.join(ROOT, 'port/tla')
    C.symbols = os.path.join(ROOT, 'port/tla/symbols')
    C.edition = 'tla-en'
    C.gen = os.path.join(ROOT, 'port_work/tla2/gen')
    C.prelude = os.path.join(ROOT, 'port/tla/shim/prelude.h')
    C.shim = os.path.join(ROOT, 'port/tla/shim')
    C.audit = os.path.join(ROOT, 'port/tla/tools/code_range_audit.tsv')
    C.overlay_bins = os.path.join(ROOT, 'port_work/tla1/overlays')
    C.pc_list = os.path.join(ROOT, 'port/tla/pc.tsv')    # the port/pc files TLA shares
    # GCC 2.9x accepted these as warnings; clang 21 makes them errors by default (-w does not lower them). Only the
    # type check changes: on the ARM a word is a word, and the IR is the same once the call is made.
    C.extra_cflags = ['-Wno-incompatible-function-pointer-types', '-Wno-int-conversion',
                      '-Wno-incompatible-pointer-types', '-Wno-return-mismatch']
else:
    raise SystemExit(f'unknown game {GAME!r} (tbs or tla)')
C.vendor = os.path.join(ROOT, 'vendor/alchemy', C.vendor_game)


def table(name):
    """Path of a per-game override table (fn_overrides.tsv, asm_rules.tsv, c_rules.tsv, overrides.tsv)."""
    return os.path.join(C.tables, name)


def sym(name):
    """Path of an address-map table; MAP and MAP-overlays stand for the edition's two symbol tables."""
    return os.path.join(C.symbols, name.replace('MAP', C.edition))


def pc_files():
    """port/pc C files this game links (relative names without .c), in order."""
    import glob
    allf = sorted(os.path.basename(p)[:-2] for p in glob.glob(os.path.join(ROOT, 'port/pc/*.c')))
    if C.pc_list is None:
        return allf
    want = []
    for line in open(C.pc_list, encoding='utf-8'):
        if line.startswith('#') or not line.strip() or line.startswith('file\t'):
            continue
        f = line.rstrip('\n').split('\t')
        if f[1] == 'yes':
            want.append(f[0])
    return [n for n in allf if n in want]


def bound_names(objs):
    """The bound module name (build/<out>/bound/NAME.ll) of each (image, object) of objs, in order: the object's
    path; for a TLA C object linked into several overlays (field/object/set_sprite_priority is in 49), path@image,
    one module per overlay, each with that overlay's ovNNN_ names (TLA2b). tbs: always the path."""
    from collections import Counter
    n = Counter(o for _, o in objs)
    return [o if (C.game == 'tbs' or n[o] == 1) else f'{o}@{i}' for i, o in objs]
